// ---- Vedic Kernels ----
inline float va(float x){float i=(x>=0)?x*1.05f:x*0.3f,p=(x>=0)?x*0.3f:x*1.05f;return 0.5f*x+0.25f*i+0.25f*p+0.1f*x;}

// ---- .vr LEXER / PARSER ----
enum TokenType { TOK_EOF, TOK_IDENT, TOK_NUMBER, TOK_LBRACE, TOK_RBRACE, TOK_ASSIGN, 
                 TOK_LBRACKET, TOK_RBRACKET, TOK_COMMA, TOK_LPAREN, TOK_RPAREN, TOK_STRING };

struct Token { TokenType type; char text[64]; float num; int line; };

struct Lexer {
    const char* src; int pos, line;
    Lexer(const char* s) : src(s), pos(0), line(1) {}
    
    Token next() {
        while (src[pos] && (src[pos]==' '||src[pos]=='\t'||src[pos]=='\n'||src[pos]=='\r')){
            if(src[pos]=='\n')line++; pos++;
        }
        if (!src[pos]) return {TOK_EOF, "", 0, line};
        if (src[pos]=='#') { while(src[pos]&&src[pos]!='\n')pos++; return next(); }
        
        Token t; t.line=line; int i=0;
        if (isalpha(src[pos])||src[pos]=='_'){
            while(isalnum(src[pos])||src[pos]=='_') t.text[i++]=src[pos++];
            t.text[i]=0; t.type=TOK_IDENT; return t;
        }
        if (isdigit(src[pos])||src[pos]=='-'){
            char num[32];int ni=0;
            if(src[pos]=='-') num[ni++]=src[pos++];
            while(isdigit(src[pos])||src[pos]=='.') num[ni++]=src[pos++];
            num[ni]=0; t.num=atof(num); t.type=TOK_NUMBER; return t;
        }
        if (src[pos]=='"'){pos++;while(src[pos]&&src[pos]!='"')t.text[i++]=src[pos++];
            t.text[i]=0;t.type=TOK_STRING;if(src[pos]=='"')pos++;return t;}
        
        char c=src[pos++];
        switch(c){
            case '{':t.type=TOK_LBRACE;break;case '}':t.type=TOK_RBRACE;break;
            case '=':t.type=TOK_ASSIGN;break;case '[':t.type=TOK_LBRACKET;break;
            case ']':t.type=TOK_RBRACKET;break;case ',':t.type=TOK_COMMA;break;
            case '(':t.type=TOK_LPAREN;break;case ')':t.type=TOK_RPAREN;break;
        }
        return t;
    }
};

// ---- TRANSPILER: .vr → C++ ----
void transpile(const char* source) {
    Lexer lex(source);
    printf("// Generated by VedaRta Compiler\n");
    printf("#include \"vr_kernels.h\"\n#include <cstdio>\nint main(){\n");
    printf("  printf(\"🕉️  VedaRta Program Output\\\\n\");\n");
    
    Token t = lex.next();
    while (t.type != TOK_EOF) {
        if (t.type == TOK_IDENT) {
            // Check for Vedic keywords
            if (strcmp(t.text,"annamaya")==0 || strcmp(t.text,"pranamaya")==0 ||
                strcmp(t.text,"manomaya")==0 || strcmp(t.text,"vijnanamaya")==0 ||
                strcmp(t.text,"anandamaya")==0) {
                printf("  // Kosha: %s\n", t.text);
                t = lex.next();
                if (t.type == TOK_LBRACE) {
                    printf("  {\n");
                    t = lex.next();
                    while (t.type != TOK_RBRACE && t.type != TOK_EOF) {
                        if (t.type == TOK_IDENT && strcmp(t.text,"output")==0) {
                            t = lex.next();
                            if (t.type == TOK_LPAREN) {
                                t = lex.next();
                                printf("    printf(\"Output: %%s\\\\n\", \"%s\");\n", t.text);
                                t = lex.next(); // )
                            }
                        } else if (t.type == TOK_IDENT) {
                            // Variable assignment or function call
                            char vname[64]; strcpy(vname, t.text);
                            t = lex.next();
                            if (t.type == TOK_ASSIGN) {
                                t = lex.next();
                                if (t.type == TOK_LBRACKET) {
                                    printf("    float %s[] = {", vname);
                                    t = lex.next();
                                    while (t.type != TOK_RBRACKET) {
                                        if (t.type == TOK_NUMBER) printf("%.1ff", t.num);
                                        t = lex.next();
                                        if (t.type == TOK_COMMA) { printf(", "); t = lex.next(); }
                                    }
                                    printf("};\n");
                                } else if (t.type == TOK_IDENT) {
                                    char func[64]; strcpy(func, t.text);
                                    t = lex.next();
                                    if (t.type == TOK_LPAREN) {
                                        t = lex.next();
                                        printf("    float %s = %s(%s);\n", vname, func, t.text);
                                        t = lex.next(); // )
                                    }
                                }
                            }
                        }
                        t = lex.next();
                    }
                    printf("  }\n");
                }
            } else {
                // Unknown identifier — skip
                t = lex.next();
            }
        } else {
            t = lex.next();
        }
    }
    printf("  return 0;\n}\n");
}

